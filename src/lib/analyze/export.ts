// Export: analysis report as Markdown and raw graph data as JSON.
// Secrets are redacted before anything leaves the app.

import type { AnalysisResult } from './types';
import { redactSecrets } from './redact';
import { missingCategories, CATEGORY_LABELS } from './graph';

export function exportJson(result: AnalysisResult): string {
  const safe: AnalysisResult = {
    ...result,
    // file contents stay local; export metadata only
    files: result.files.map((f) => ({ path: f.path, content: '', size: f.size, language: f.language })),
    warnings: result.warnings.map(redactSecrets),
  };
  return JSON.stringify(safe, null, 2);
}

export function exportMarkdown(result: AnalysisResult): string {
  const L: string[] = [];
  L.push(`# CodeAtlas Analysis: ${result.projectName}`);
  L.push('');
  L.push(`- Scanned: ${result.scannedAt}`);
  L.push(`- Files analyzed: ${result.stats.analyzedFiles} (ignored: ${result.ignoredCount}, skipped oversized: ${result.stats.skippedOversize})`);
  L.push('');
  L.push('## Technologies');
  L.push('');
  for (const t of result.technologies) {
    L.push(`- **${t.name}** (${t.category}) — ${t.confidence}, evidence: ${t.kind}${t.version ? `, version ${t.version}` : ''}`);
  }
  L.push('');
  L.push('## API Endpoints');
  L.push('');
  if (result.endpoints.length) {
    L.push('| Method | Path | Handler | File |');
    L.push('|---|---|---|---|');
    for (const e of result.endpoints) {
      L.push(`| ${e.method} | \`${e.path}\` | ${e.handler ?? '—'} | ${e.file}:${e.line} |`);
    }
  } else {
    L.push('No API endpoints detected.');
  }
  L.push('');
  L.push('## Database Models');
  L.push('');
  if (result.dbModels.length) {
    for (const m of result.dbModels) L.push(`- **${m.name}** — ${m.file}${m.line ? `:${m.line}` : ''}`);
  } else {
    L.push('No database models detected.');
  }
  L.push('');
  L.push('## Entry Points');
  L.push('');
  for (const e of result.entryPoints) L.push(`- ${e}`);
  if (!result.entryPoints.length) L.push('- None identified.');
  L.push('');
  L.push('## Environment Variables (names only, values never read)');
  L.push('');
  for (const v of result.envVars.slice(0, 40)) L.push(`- \`${v.name}\` (referenced in ${v.file})`);
  if (!result.envVars.length) L.push('- None detected.');
  L.push('');
  L.push('## Important Files');
  L.push('');
  for (const f of result.files.filter((f) => /package\.json|requirements\.txt|pyproject\.toml|Dockerfile|docker-compose|\.env\.example|vite\.config|tsconfig/.test(f.path)).slice(0, 30)) {
    L.push(`- ${f.path}`);
  }
  L.push('');
  const missing = missingCategories(result);
  L.push('## Not Detected');
  L.push('');
  L.push(missing.length ? missing.map((c) => `- ${CATEGORY_LABELS[c]}`).join('\n') : '- All standard categories had some evidence.');
  L.push('');
  L.push('## Warnings');
  L.push('');
  if (result.warnings.length) for (const w of result.warnings) L.push(`- ${redactSecrets(w)}`);
  else L.push('- None.');
  L.push('');
  L.push('## Limitations');
  L.push('');
  for (const lim of result.limitations) L.push(`- ${lim}`);
  L.push('');
  L.push('_Generated by CodeAtlas. Analysis is static; no code was executed. Secret values were redacted._');
  return L.join('\n');
}

export function downloadText(filename: string, text: string, mime = 'text/plain'): void {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 5000);
}
